# Run with Rscript after installing R. Uses a user library, not system packages.
args <- commandArgs(trailingOnly = FALSE)
file_arg <- sub("^--file=", "", args[grepl("^--file=", args)])
base <- dirname(normalizePath(file_arg[[1]]))
lib <- path.expand(sprintf("~/Library/R/%s/library", paste(R.version$major, strsplit(R.version$minor, ".", fixed = TRUE)[[1]][1], sep = ".")))
dir.create(lib, recursive = TRUE, showWarnings = FALSE)
.libPaths(c(lib, .libPaths()))
options(repos = c(CRAN = "https://cloud.r-project.org"), timeout = 600, Ncpus = 4)
if (!requireNamespace("remotes", quietly = TRUE)) install.packages("remotes", lib = lib)
if (!requireNamespace("jsonlite", quietly = TRUE)) install.packages("jsonlite", lib = lib)
source <- jsonlite::fromJSON(file.path(base, "clauder-source.json"))
remotes::install_github(paste0(source$repo, "@", source$sha), lib = lib, dependencies = NA, upgrade = "never", build_vignettes = FALSE)
stopifnot(requireNamespace("ClaudeR", quietly = TRUE))
cat("ClaudeR", as.character(packageVersion("ClaudeR")), "installed in", lib, "\n")
